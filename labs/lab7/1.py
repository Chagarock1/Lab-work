smart_home = {
    "Лампа у вітальні": "увімкнено",
    "Кондиціонер": "вимкнено",
    "Телевізор": "вимкнено",
    "Робот-пилосос": "увімкнено",
    "Зволожувач повітря": "вимкнено",
    "Бойлер": "увімкнено"
}

print("Початковий стан розумного дому:")
for device, state in smart_home.items():
    print(f"- {device}: {state}")

smart_home["Кондиціонер"] = "увімкнено"
print("\n[Оновлення] Змінено стан кондиціонера на 'увімкнено'.")

smart_home["Кавоварка"] = "увімкнено"
print("[Додавання] Додано новий пристрій: Кавоварка (увімкнено).")

turned_on = [device for device, state in smart_home.items() if state == "увімкнено"]

print("\nСписок увімкнених пристроїв:")
for device in turned_on:
    print(f"  - {device}")

print(f"\nЗагальна кількість увімкнених пристроїв: {len(turned_on)}")
