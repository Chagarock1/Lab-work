print("Розробник: 'Отримаємо довжину рядка через len() і класифікуємо його за діапазонами.'")

password = input("Введіть пароль для оцінки: ")

if len(password) < 8:
    print("Слабкий пароль")
elif 8 <= len(password) <= 12:
    print("Середній пароль")
elif len(password) > 12:
    print("Надійний пароль ")
