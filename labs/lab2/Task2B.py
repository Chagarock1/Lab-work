print('Математик: «Чи належить введено число X до послідовності Фібоначчі?» ')
print('Розробник: "Генеруватимемо числа Фібоначчі у циклі while b < X. Якщо в кінці b == X, то число належить послідовності."')

x = int(input("Введіть ціле число: "))
a = 1
b = 1

while b < x:
    a, b = b, a + b

if b == x:
    print("Так")
else:
    print("Ні")
