print("Математик: «Перевіримо цікаву властивість трицифрового числа: чи дорівнює (d1 + d2 + d3)^2 значенню d1^3 + d2^3 + d3^3 ?»")
print("Розробник: «Розкладемо число на цифри, обчислимо обидва вирази та порівняємо їх через ==.»")

numbers = input("Введіть ціле трицифрове число: ")

d1 = int(numbers[0])
d2 = int(numbers[1])
d3 = int(numbers[2])

s1 = (d1+d2+d3)**2
s2 = d1**3 + d2**3 + d3**3

if s1 == s2:
    print("Рівність виконується")
else:
    print("Рівність не виконується")  
